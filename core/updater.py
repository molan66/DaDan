# v4.6.6: 修"关闭程序后进程不退出 + C 盘堆垃圾"(排查上一条时顺带发现的)。
#          现象: 用户关掉程序后仍有两个进程残留, 非提权方式杀不掉。实测那些
#          进程卡在一个 **PyInstaller 自己的**模态警告框上:
#              "Failed to remove temporary directory: ...\Temp\_MEI00003fc02"
#          根因: onefile 模式要把整包解压到系统临时目录, 退出时再删; 而
#          VCRUNTIME140*.dll 在进程存活期间一直被加载着, 删除必然失败 →
#          PyInstaller 弹框 → 进程永远停在那里。查 C 盘 Temp 发现堆了 **37 个**
#          _MEI* 目录(147.88 MB), 其中 **31 个是空目录** —— 说明文件基本删掉了,
#          只有目录本身没删掉(退出瞬间还被占用, 属时序问题, 事后随手可删)。
#          两处修:
#          ① main 新增 _cleanup_stale_runtime_dirs(): 启动时补一刀, 扫系统 Temp
#             里的历史 _MEI* 删掉, 让垃圾不累积。进程退出那一刻它自己的目录注定
#             删不干净(那两个 dll 还映射着), 与其在退出路径上较劲, 不如交给下一
#             次启动。三条安全边界: 只扫 Temp 下的 _MEI*、比对 sys._MEIPASS 跳过
#             当前实例、删不掉就跳过(实测会跳过正在跑的实例)。
#          ② **试过但放弃**的方案(勿重复尝试): 用 build.spec 的 runtime_tmpdir
#             把解压目录挪到 exe 同级。实测两个致命问题 ——
