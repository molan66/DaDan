#                 从不同位置启动会落到意外路径, 甚至因无权限直接启动失败;
#               · 绝对路径: 会被逐字写进 exe(bootloader 选项 pyi-runtime-tmpdir),
#                 等于硬编打包机路径, 换台机器就失效。
#             故 spec 里**有意不设** runtime_tmpdir, 保持 PyInstaller 默认。
