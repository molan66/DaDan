#          【v4.6.13 为什么没修住: 补丁补在了永远走不到的分支里】
#          那句 _set_conn_state('connected') 写在 _apply_ui_connected 的
#          `if connected and not self._ui_connected:` **跃迁分支内部** —— 于是三态
#          不是"由事实推导", 而是"跃迁时顺带触发的一次性动作"。只要有一次
#          interleaving 把琥珀盖上去, 之后所有置绿都是**非跃迁 no-op**, 三态通道
#          再没有任何机会被纠正。(上一版把"0 次调用 'connected'"当成根因, 对了一半:
#          接线接上了, 但接在一条只在特定跃迁时才通电的线上。)
#          【真实 interleaving —— 日志顺序就是证据】
#          REST 探活与 WS 是两条独立通道, 且 REST **通常先成功**:
#            t0 3s 探活 → 置绿(跃迁)
#            t1 5s _try_connect: WS 尚 on_open(is_connected=False), 而它只判
#               ws/单飞, **完全不看 _ui_connected** → 把琥珀重新盖上去
#            t2 [WS] on_open → 置绿, 但已非跃迁 → no-op → 停在琥珀
#            t3 此后每 3s no-op, 每 5s 还在补琥珀
#          取证: dist/data/logs/app.log 中 `[App] 已连接客户端（…）`(3771)
#          确实早于 `[WS] on_open 成功`(3789); 即 t0 先于 t2。
#          【修法: 收口 + 幂等】
#          把"谁写三态"收成一个函数 _sync_conn_state(): 按当前事实(已连接 > 连接中
#          > 未连接)算目标值, 与"屏上当前值"(_conn_state_shown)比较, 相同就不推。
#          原先四处各自 _set_conn_state 的写点(_try_connect / _settle_connecting /
#          _apply_ui_connected / _on_start_done)全部改为调它。判据保留 WS 权威语义:
#          _ui_connected 为真**或** WS 已 on_open 都算已连接。
#          _settle_connecting 里先清 _connecting 再同步 —— 否则会按"仍在连接中"
#          又推一次琥珀、反而 settle 不掉(该函数在 worker 的 finally 之前被调)。
#          幂等是必须的: _do_conn_state 每次调用都会停掉三点跳动动画, 而同步会跟着
#          3s 周期的探活一起跑 —— 无条件重推会把"等待匹配…"的动画每 3s 掐死一次。
#          另: _on_start_done 原用 set_conn_indicator(self._conn.is_connected, …)
#          决定颜色, 而 is_connected 只是"端口/令牌非 None"的判空、**不探活**, 会
#          造成"WS 已连上、界面却被打成未连接"的第三种撕裂; 一并改走收口点。
